def b(text):
    return {"text": join_lines(text) if isinstance(text, list) else text}


def _exp(template, fn, ex):
    if isinstance(template, list):
        return [line.replace("{FN}", fn).replace("{EX}", ex) for line in template]
    return template.replace("{FN}", fn).replace("{EX}", ex)


def topic(names, examples, body_tmpl, demo_tmpl=None):
    out = []
    for fn in names:
        for ex in examples:
            body = _exp(body_tmpl, fn, ex)
            # Unique prefix per pair so dedup-by-first-200-chars works
            # when the same fn has multiple examples with identical bodies.
            body = ["# " + fn + " :: " + ex] + body
            if demo_tmpl is not None:
                body += [""] + _exp(demo_tmpl, fn, ex)
            out.append(b(body))
    return out


