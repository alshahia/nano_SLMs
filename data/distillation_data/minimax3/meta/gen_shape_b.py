def main():
    shape = "shape_b_completion"
    index = 1
    total = 0
    for name, names, examples, body_tmpl, demo_tmpl in TOPICS:
        pairs = topic(names, examples, body_tmpl, demo_tmpl)
        kept, dropped, _ = write_pairs(shape, index, pairs, verbose=True)
        total += kept
        index += 1
    print(f"\nShape B total: kept={total} across {index - 1} generator batches")


if __name__ == "__main__":
    main()
