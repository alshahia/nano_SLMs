#!/usr/bin/env python3
"""Shape B programmatic builder for gen_topup4.

Builds B_TOPICS as a programmatically-generated list to avoid the 8+ failed
hand-written drafts that collided with existing corpus topics (every common
helper name like 'take', 'drop', 'pairwise' is already covered by the
existing 3,647 B pairs).

Strategy:
  * qx2_ prefix on every fn name (collisions reported were qx_ names; qx2_
    is fresh).
  * All non-string examples converted to repr() (B's body does string
    concat on ex, so lists/dicts/tuples must already be valid Python
    literal strings).
  * Lambda examples use 'pred_src: str' inside the body (make_b can't
    pickle a lambda literal).
  * No-arg topics (no inputs) get distinct sentinel examples so the
    3 names * 5 examples = 15 pairs/topic yield doesn't collapse to
    duplicates.

Yields ~3 names * 5 examples = 15 pairs/topic. With 150 topics: ~2250 pairs.
File index range: batch_g1000..batch_g1149.
"""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))


def _repr_ex(ex):
    if isinstance(ex, str):
        return ex
    return repr(ex)


def _topic(name, fn_names, examples, body_lines, demo_lines=None):
    """Build a B_TOPICS tuple (cat, names, examples, body, demo)."""
    return (name,
            fn_names,
            [_repr_ex(e) for e in examples],
            body_lines,
            demo_lines)


# Stats / math helpers ---------------------------------------------------------
def _stat(name, op):
    return _topic(
        f"qx2_stat_{name}",
        [f"qx2_{name}", f"qx2_{name}_run", f"qx2_run_{name}"],
        ["[1, 2, 3, 4, 5]", "[10]", "[1.5, 2.5, 3.5]", "[-1, 0, 1]", "[5, 5, 5, 5]"],
        ["import statistics",
         "",
         f"def {{FN}}(xs):",
         f"    return statistics.{op}(xs)"],
        ["if __name__ == '__main__':", "    print({FN}({EX}))"])


