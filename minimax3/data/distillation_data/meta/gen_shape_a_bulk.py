"""Shape A generator: {instruction, response} pairs (data-driven template).

Each topic is (name_variants, example_inputs, body_template, instruction_template).
The generator emits len(names) * len(examples) pairs per topic, with {FN}/{EX}
substituted in both the instruction and each code line. The body_template is
literal code; {} markers are simple string replacements (str.replace, not
str.format), so unused placeholders do NOT raise.

All pairs are validated by gen_lib.write_pairs (ast.parse on the response).

Run:  & .venv/Scripts/python.exe meta/gen_shape_a_bulk.py
Out:  shape_a_instruction_code/batches/batch_gNNN.jsonl  (one per topic)
"""
import sys
