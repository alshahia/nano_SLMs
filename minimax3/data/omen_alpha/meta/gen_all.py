def pair(instruction, code_lines):
    return {"instruction": instruction.strip(), "response": join_lines(code_lines)}


def _strip_outer_parens(ex):
    """Strip a single outer paren-wrap from a multi-arg example (HANDOFF 16 fix)."""
    if not (ex.startswith('(') and ex.endswith(')')):
        return ex
    depth = 0
    top_commas = 0
    for c in ex:
        if c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
            if depth == 0 and c != ex[-1]:
                return ex
        elif c == ',' and depth == 1:
            top_commas += 1
    if top_commas >= 1 or ex.endswith(',)'):
        return ex[1:-1].strip()
    return ex


def _expand(template, fn, ex):
    ex_clean = _strip_outer_parens(ex)
    if isinstance(template, list):
        return [line.replace("{FN}", fn).replace("{EX}", ex_clean) for line in template]
    return template.replace("{FN}", fn).replace("{EX}", ex_clean)


def run_a(index, names, examples, body_tmpl, instr_tmpl):
    out = []
    for fn in names:
        for ex in examples:
            out.append(pair(_expand(instr_tmpl, fn, ex), _expand(body_tmpl, fn, ex)))
    kept, dropped, _ = write_pairs(SHAPE_A, index, out)
    return kept


def run_b(index, names, examples, body_tmpl, demo_tmpl):
    out = []
    for fn in names:
        for ex in examples:
            body = [line.replace("{FN}", fn).replace("{EX}", ex) for line in body_tmpl]
            text = ["# " + fn + " :: " + ex] + body
            if demo_tmpl is not None:
                text += [""] + [line.replace("{FN}", fn).replace("{EX}", ex) for line in demo_tmpl]
            out.append({"text": join_lines(text)})
    kept, dropped, _ = write_pairs(SHAPE_B, index, out)
    return kept


def run_c(index, names, labels, fixed_tmpl, instr_tmpl):
    out = []
    for fn in names:
        for ex in labels:
            body = [line.replace("{FN}", fn) for line in fixed_tmpl]
            instr = instr_tmpl.replace("{FN}", fn) + " (input: " + ex + ")"
            out.append(pair(instr, body))
    kept, dropped, _ = write_pairs(SHAPE_C, index, out)
    return kept


def run_d(index, problems, prose_main, prose_tail, code_lines):
    BT = chr(96) * 3
    out = []
    for problem in problems:
        prose = prose_main + chr(10) + chr(10) + prose_tail.replace("{PROBLEM}", problem)
        response = (prose + chr(10) + chr(10)
                    + BT + "python" + chr(10) + join_lines(code_lines) + BT + chr(10))
        out.append({"instruction": problem.strip(), "response": response})
    kept, dropped, _ = write_pairs(SHAPE_D, index, out)
    return kept


def _probs(fmt, data):
    """Build 20 unique problem statements from (fmt, data) with .format."""
    out = []
    for d in data:
        if isinstance(d, tuple):
            out.append(fmt.format(*d))
        else:
            out.append(fmt.format(d))
    return out


